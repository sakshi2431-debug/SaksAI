import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Generate the Worker's content from the same reviewed Markdown used for indexing.
const directory = new URL("../portfolio-knowledge/", import.meta.url);
const files = (await readdir(directory)).filter(file => file.endsWith(".md")).sort();
const docs = await Promise.all(files.map(async file => ({
  slug: file.replace(/\.md$/, "").toLowerCase(),
  content: await readFile(new URL(file, directory), "utf8"),
})));
const output = new URL("../sakllm-worker/floral-rain-aae6/src/knowledgeBase.js", import.meta.url);
await writeFile(output, `// Generated by npm run sync-kb; edit portfolio-knowledge/*.md instead.\nexport function loadKnowledgeBase() {\n  return ${JSON.stringify(docs, null, 2)};\n}\n`);
console.log(`Generated ${docs.length} documents: ${fileURLToPath(output)}`);
